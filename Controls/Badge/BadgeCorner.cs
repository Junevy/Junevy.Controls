namespace Junevy.Controls.Controls.Badge;

/// <summary>
/// Badge 角标的停靠角落：表示角标中心停靠在包裹内容（控件）的哪一个角落。
/// </summary>
public enum BadgeCorner
{
    /// <summary>停靠左上角。</summary>
    TopLeft,

    /// <summary>停靠右上角（默认）。</summary>
    TopRight,

    /// <summary>停靠左下角。</summary>
    BottomLeft,

    /// <summary>停靠右下角。</summary>
    BottomRight,
}
